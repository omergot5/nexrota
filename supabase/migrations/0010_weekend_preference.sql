-- ============================================================
-- העדפת סופ"ש: רכה, אישית, לא-חוסמת.
--
-- שישי-שבת בישראל הם דוגמה קלאסית לצוות עם שני צרכים מנוגדים באותה
-- משמרת: מי שלא רוצה לעבוד בהן (מסיבות דת, משפחה, כל סיבה אחרת שהאדם
-- לא חייב לגלות) לעומת מי שדווקא מעדיף/ה אותן (תגמול סופ"ש גבוה יותר).
-- הפתרון הוא לא דגל זהות ("שומר/ת שבת") — זו לא עמודה שהמוצר הזה שואל,
-- כי היא מכריחה אדם להצהיר על עצמו כדי לקבל שיבוץ הוגן. זו העדפת
-- לו"ז גרידא, סימטרית: אפשר לרצות פחות סופ"ש, ואפשר לרצות יותר.
--
--   gs_profiles.weekend_preference   'avoid' | 'prefer' | NULL.
--     NULL (ברירת מחדל) = בלי העדפה מיוחדת, בדיוק כמו qualified_categories
--     ריק ב-0006_qualification.sql. text ולא boolean כי אלה שני כיוונים
--     אמיתיים, לא דגל אחד — 'avoid'=false היה מבטל את האפשרות להביע
--     'prefer' מבלי להמציא עמודה שנייה.
--
--     קשה בכוונה, לא רך: המנוע (autoAssign.js scoreCandidate) קורא את זה
--     כניקוד רך שדוחף/מושך משמרת סופ"ש, לעולם לא כאילוץ קשיח. מי שסימן/ה
--     "מעדיף/ה לא לעבוד" עדיין *יכול/ה* להישבץ לשישי-שבת אם אין ברירה —
--     בדיוק כמו ש"מעדיף/ה" (העדפת משמרת בודדת, autoAssign.js קיים) לא
--     עוקף הוגנות. חסימה אמיתית, אם ירצו כזו יום אחד, היא שיחת מוצר
--     נפרדת — לא תופעת לוואי של העמודה הזאת.
-- ============================================================

alter table gs_profiles add column if not exists weekend_preference text
  check (weekend_preference in ('avoid', 'prefer'));
