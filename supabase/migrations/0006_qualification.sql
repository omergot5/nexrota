-- כשירות: רשימת קטגוריות לאדם, וקטגוריית עבודה למשמרת.
--
-- שתי עמודות בלבד, שתיהן nullable ובלי ברירת מחדל — ולכן ההרצה בטוחה
-- על טבלה מלאה ולא נוגעת בשורה קיימת אחת. אין כאן update, בכוונה: רשימה
-- ריקה פירושה "כשיר/ה לכול" (QUAL-02, D-03), ומילוי שלה לאחור היה הופך
-- כל אדם קיים מבלי-הגבלה למוגבל-למה-שבמקרה היה קיים באותו יום — ההיפוך
-- המדויק של default-deny שהמפה מזהה כסיכון הראשון של הפאזה הזאת. NULL
-- והמערך הריק אמורים לספר את אותו סיפור, אז שכבת הכתיבה (setGuardQualifications
-- ב-api.js) מנרמלת מערך ריק בחזרה ל-NULL, כדי שבבסיס הנתונים לעולם לא
-- יהיו שני איות לאותו מצב.
--
--   gs_profiles.qualified_categories   מערך הקטגוריות שהאדם כשיר להן.
--     jsonb ולא Postgres text[] (P-01 ב-03-02-PLAN.md): הסכמה הזאת כבר
--     שומרת שני מערכי אנשים/עמדות בדיוק כך (gs_tasks.assignees מ-0002,
--     gs_task_templates.positions מ-0004), וזה הדפוס המקומי המבוסס.
--     isQualified קורא לה רק עם Array.isArray ו-.includes — שום קוד לא
--     תלוי בטיפוס העמודה המדויק.
--   gs_shifts.category   סוג העבודה, נפרד מ-type (שעת היום). מוקלד text
--     בדיוק כמו עמודת category הקיימת על gs_tasks, כי D-01/D-02 הופכים
--     טקסונומיה אחת משותפת לשתי הישויות — עמודת ה-category הקיימת על
--     gs_tasks *היא עצמה* שדה הכשירות של המשימה; אין כאן ואין בשום מקום
--     אחר עמודה שנייה על טבלת המשימות.
-- ============================================================

alter table gs_profiles add column if not exists qualified_categories jsonb;
alter table gs_shifts add column if not exists category text;
