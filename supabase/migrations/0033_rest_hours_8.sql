-- ============================================================
-- מנוחה מינימלית של 8 שעות: אפשרות שלישית ליד 10 ו-12.
--
-- בצבא, עם כוננות של 6 במקביל, סיור של 3–4 ושמירה סביב השעון, מנוחה של 10
-- שעות בין תורנויות משאירה מקומות פתוחים (נמדד: 175/181 במקום 179/181, וחמש
-- משמרות פיקוד בלי בעל תפקיד במקום אחת). ההגדרה נשארת בידי המפקד — 10 היא
-- ברירת המחדל, ו-8 היא אפשרות, לא ברירת מחדל שנכפית.
--
-- gs_teams.rest_hours: 8, 10 או 12 (היה 10 או 12, ר' 0020).
-- ============================================================

alter table gs_teams drop constraint if exists gs_teams_rest_hours_check;
alter table gs_teams add constraint gs_teams_rest_hours_check check (rest_hours in (8, 10, 12));
