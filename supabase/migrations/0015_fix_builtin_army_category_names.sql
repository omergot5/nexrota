-- ============================================================
-- תיקון: כללי ההתנגשות המובנים (gs_role_compatibility, team_code null)
-- השתמשו בשמות קטגוריה שלא קיימים בפועל בטקסונומיית הצבא.
--
-- חמשת הכללים המובנים כבר היו בבסיס הנתונים לפני שהיה מסך שמראה אותם
-- (ר' 0014) — אבל הם נכתבו עם "מטבח"/"שמירות", בעוד ש-FOLDERS_BY_MODE.army
-- (views.jsx) מציע בפועל "תורנות מטבח"/"תורנות שמירה". התאמת מחרוזות
-- מדויקת (pairKey ב-conflicts.js) פירושה שהכללים האלה מעולם לא תפסו שום
-- התנגשות אמיתית בצוות צבאי אמיתי — רק בזוג-קטגוריות שאף אחד לא הקליד.
--
-- כוננות עצמה הייתה חסרה לגמרי מ-FOLDERS_BY_MODE.army, למרות שהיא צד
-- בשניים מחמשת הכללים המובנים — תוקן גם ב-views.jsx, לא רק כאן.
-- ============================================================

delete from gs_role_compatibility
  where team_code is null and (a in ('מטבח', 'שמירות') or b in ('מטבח', 'שמירות'));

-- NOT EXISTS ולא VALUES רגיל: המיגרציה הזו הופעלה חיה על בסיס הנתונים
-- (via execute_sql) לפני שנרשמה כאן, אז הכתיבה חייבת להיות אידמפוטנטית
-- כדי שהרצה נוספת (אם הטבלה תישחזר, או בסביבה אחרת) לא תשכפל שורות.
insert into gs_role_compatibility (team_code, a, b, rule, note)
select null, v.a, v.b, 'block', v.note
from (values
  ('כוננות', 'תורנות מטבח', 'כוננות היא זמינות, לא נוכחות — אפשר להיות בכונן ולעבוד במטבח'),
  ('תורנות מטבח', 'תורנות שמירה', 'עמדת שמירה דורשת נוכחות פיזית רצופה'),
  ('סיור', 'תורנות שמירה', 'אי אפשר לאייש עמדה ולנוע בו־זמנית'),
  ('כוננות', 'תורנות שמירה', 'עמדה מאיישת — היא לא כוננות'),
  ('סיור', 'תורנות מטבח', 'סיור הוא תנועה מחוץ למטבח')
) as v(a, b, note)
where not exists (
  select 1 from gs_role_compatibility r
  where r.team_code is null and r.a = v.a and r.b = v.b
);
