-- משקל הוגנות לפי קטגוריה — "אף אחד לא רוצה מטבח, כולם רוצים כוננות".
--
-- shiftLoad() (autoAssign.js) הוא יחידת ההוגנות היחידה במוצר, ועד עכשיו
-- ידע לשקלל רק סוג-משמרת וסופ"ש. אין לו מושג של "התפקיד הזה פחות רצוי".
-- הצבא הוא המקרה שבו זה מתפרץ: משמרת מטבח ומשמרת כוננות יכולות להיות
-- באותו אורך שעות בדיוק ולהרגיש הפוך לגמרי מבחינת מי שעושה אותן.
--
--   gs_teams.task_weights   jsonb, ברירת מחדל '{}'.
--     מפה {קטגוריה: מכפיל}, למשל {"מטבח": 1.4, "כוננות": 0.6} — אותו
--     כיוון בדיוק כמו LOAD_WEIGHTS.night (1.4): מכפיל גבוה = "משמרת
--     כזו ממצה יותר מהיעד האישי", אז מטבח (לא רצוי) מקבל מכפיל גבוה
--     כדי להגן על מי שעשה אותו מעומס נוסף בקרוב, וכוננות (רצוי) מכפיל
--     נמוך כי אין ממה להגן. קטגוריה שלא מופיעה במפה מקבלת מכפיל 1 —
--     בדיוק ההתנהגות מלפני המיגרציה הזו, לכל צוות שלא נגע באפשרות.
--     מוגדר ברמת הצוות ("באופן כללי, לא פר בן אדם" — כפי שהוגדר) ולא
--     פר-אדם: אין עמודה מקבילה על gs_profiles, כי זה בכוונה לא מאפיין
--     אישי.
--
--     רך, לא חוסם — בדיוק כמו weekend_preference (0010) ו-half_time
--     (0012): shiftLoad() משתמש בזה בתור מכפיל על משקל, לא ב-
--     checkHardConstraints בתור אילוץ. מי שאין ברירה עדיין יכול/ה
--     להישבץ לקטגוריה הכי פחות רצויה.
-- ============================================================

alter table gs_teams add column if not exists task_weights jsonb not null default '{}'::jsonb;
