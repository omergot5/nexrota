--
--   gs_profiles.color_slot   smallint, NULL כברירת מחדל.
--     NULL = עוד לא נקבע, והצבע מחושב ומקבל משבצת בכניסה הבאה של המפקד.
--     צוות הדגמה לא נשמר (הנתונים שלו נמחקים), ולכן נשאר NULL ומחושב.
--
-- אותה טבלה ואותה מדיניות RLS כמו half_time (0012): מי שיכול לעדכן פרופיל
-- יכול לעדכן גם את זה. אין עמודה חדשה שנחשפת למי שלא ראה את הפרופיל קודם.
-- ============================================================

alter table gs_profiles add column if not exists color_slot smallint
  check (color_slot is null or (color_slot >= 0 and color_slot < 36));
